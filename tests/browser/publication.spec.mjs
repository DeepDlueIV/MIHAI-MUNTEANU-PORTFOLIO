import { test, expect, chromium, firefox } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';

const baseURL = 'http://127.0.0.1:4321';
const routes = ['/', '/privacy/', '/terms-of-service/'];
const markers = /\bDEMO\b|concept stud(?:y|ies)|concept projects|illustrative system|not client engagements|proposed software|\bplaceholder\b|lorem ipsum|coming soon|under construction|test mode|AI[- ]generated|generated by|\bTODO\b|\bTBD\b/i;
await mkdir('qa', { recursive: true });

for (const [name, engine] of Object.entries({ chromium, firefox })) {
 test(`publication copy and links on every page / ${name}`, async () => {
  const browser = await engine.launch();
  const context = await browser.newContext({ baseURL, javaScriptEnabled: false, viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const inventory = [];
  try {
   for (const path of routes) {
    const response = await context.request.get(path);
    expect(response.status()).toBe(200);
    await page.goto(path);
    const text = await page.locator('body').innerText();
    expect(text).not.toMatch(markers);
    expect(text).not.toMatch(/DataForge|Nabil|Microsoft|OpenAI|ChatGPT|Codex/i);
    await expect(page.locator('h1')).toHaveCount(1);
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    const metadata = await page.locator('meta[name="description"], meta[property^="og:"]').evaluateAll(els => els.map(e => e.content));
    const labels = await page.locator('[aria-label], [title], [alt]').evaluateAll(els => els.map(e => [e.getAttribute('aria-label'), e.getAttribute('title'), e.getAttribute('alt')].filter(Boolean).join(' ')));
    expect([await page.title(), ...metadata, ...labels].join(' ')).not.toMatch(markers);
    expect(await page.locator('meta[name="description"]').getAttribute('content')).toBeTruthy();
    const hrefs = await page.locator('a').evaluateAll(els => els.map(e => e.getAttribute('href')));
    expect(hrefs).not.toContain('#');
    expect(hrefs.filter(h => h?.startsWith('mailto:')).length).toBeGreaterThan(0);
    for (const href of hrefs.filter(h => h?.startsWith('mailto:'))) {
     expect(decodeURIComponent(href.slice(7).split('?')[0])).toBe('mihai.muntenau@inbox.eu');
    }
    for (const href of new Set(hrefs.filter(h => h?.startsWith('/') || h?.startsWith('#')))) {
     const target = new URL(href, page.url());
     expect(routes).toContain(target.pathname);
     const linked = await context.request.get(target.pathname);
     expect(linked.status()).toBe(200);
     if (target.hash) expect(await linked.text()).toContain(`id="${decodeURIComponent(target.hash.slice(1))}"`);
    }
    for (const width of [1440, 768, 360]) {
     await page.setViewportSize({ width, height: 1000 });
     expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(path);
    const key = path === '/' ? 'home' : path.split('/')[1];
    await page.screenshot({ path: `qa/${name}-publication-${key}.png`, fullPage: true });
    if (path === '/') {
     await expect(page.locator('#work')).toContainText(/Integration patterns/i);
     expect(text).not.toMatch(/selected work|client success|testimonial|years of experience/i);
    }
    inventory.push({ path, title: await page.title(), text, metadata, labels, hrefs });
   }
   await writeFile(`qa/${name}-publication-text.json`, JSON.stringify(inventory, null, 2));
  } finally { await browser.close(); }
 });
}

test('initial Full mode matches the runtime default before modules load', async ({ page }) => {
 await page.emulateMedia({ reducedMotion: 'reduce' });
 await page.route('**/*.js', route => route.abort());
 await page.goto('/');
 await expect(page.locator('html')).toHaveAttribute('data-motion', 'full');
});
